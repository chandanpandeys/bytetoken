"""ByteToken synthetic developer-payload benchmark.

Historical note: this file keeps its original ``benchmark_realworld.py`` name
for compatibility, but its payloads are generated by this script.  They are
synthetic developer-like data, not independently collected production traces.

All string encodings in this benchmark are constructed and counted with the
same target tokenizer (``o200k_base``).  Direct-ID counts are local token-ID
representation counts and do not imply that a hosted API accepts arbitrary
pre-tokenized input IDs.

Run from the repository root after installing dependencies:

    python benchmarks/benchmark_realworld.py
"""

import base64
import json
import lzma
import random
import struct

import tiktoken

from bytetoken.core import ByteTokenEncoder, DirectIDEncoder

TARGET_TOKENIZER = "o200k_base"


def count_tokens(text: str) -> int:
    """Count text tokens with the benchmark target tokenizer."""
    return len(tiktoken.get_encoding(TARGET_TOKENIZER).encode(text))


def generate_synthetic_payloads() -> dict[str, bytes]:
    """Create deterministic developer-like payloads for controlled comparison."""
    payloads: dict[str, bytes] = {}

    api_response = {
        "status": "success",
        "data": {
            "users": [
                {
                    "id": i,
                    "name": f"User_{i}",
                    "email": f"user{i}@example.test",
                    "role": "developer" if i % 3 == 0 else "viewer",
                    "last_login": f"2026-08-{(i % 28) + 1:02d}T14:30:00Z",
                    "metadata": {
                        "projects": [f"proj-{j}" for j in range(5)],
                        "commits": i * 47,
                    },
                }
                for i in range(100)
            ],
            "pagination": {"page": 1, "total": 2847, "per_page": 100},
        },
    }
    payloads["JSON API (100 users)"] = json.dumps(
        api_response, sort_keys=True
    ).encode("utf-8")

    pytest_lines = [
        "=" * 60,
        "PYTEST SESSION STARTS",
        "=" * 60,
        "platform linux -- Python 3.12.0",
        "",
    ]
    for i in range(50):
        if i % 10 == 7:
            pytest_lines.extend(
                [
                    f"FAILED tests/test_auth.py::test_login_{i} - AssertionError: expected 200 got 401",
                    f"  File \"tests/test_auth.py\", line {100 + i}, in test_login_{i}",
                    "    assert response.status_code == 200",
                    "  AssertionError: 401 != 200",
                ]
            )
        else:
            pytest_lines.append(f"PASSED tests/test_auth.py::test_login_{i}")
    pytest_lines.extend(["", "=" * 60, "5 failed, 45 passed in 12.34s", "=" * 60])
    payloads["Pytest-style output"] = "\n".join(pytest_lines).encode("utf-8")

    csv_lines = ["timestamp,user_id,action,duration_ms,status,endpoint"]
    for i in range(500):
        csv_lines.append(
            f"2026-08-27T{i // 60:02d}:{i % 60:02d}:00Z,user_{i % 50},GET,{50 + i * 3},200,/api/v2/data"
        )
    payloads["CSV analytics (500 rows)"] = "\n".join(csv_lines).encode("utf-8")

    code_lines = [
        '"""Synthetic authentication module."""',
        "import hashlib",
        "import hmac",
        "",
    ]
    for i in range(30):
        code_lines.extend(
            [
                f"def validate_token_{i}(token: str, secret: str) -> bool:",
                f'    """Synthetic validator {i}."""',
                "    if not token:",
                "        return False",
                "    return hmac.compare_digest(",
                "        hmac.new(secret.encode(), token.encode(), hashlib.sha256).hexdigest(),",
                "        token,",
                "    )",
                "",
            ]
        )
    payloads["Python source"] = "\n".join(code_lines).encode("utf-8")

    log_lines = []
    for i in range(200):
        log_lines.append(
            f"[2026-08-27T14:{i // 60:02d}:{i % 60:02d}.{i * 7 % 1000:03d}Z] INFO Building layer {i + 1}/200"
        )
        if i % 40 == 39:
            log_lines.append(
                f"[2026-08-27T14:{i // 60:02d}:{i % 60:02d}.000Z] WARN Deprecated package libfoo-{i}"
            )
    payloads["Build-log text"] = "\n".join(log_lines).encode("utf-8")

    embedding = struct.pack(
        "768f", *[0.1 * (i % 100 - 50) for i in range(768)]
    )
    payloads["Embedding vector (768 float32)"] = embedding

    # Deterministic high-entropy-ish control so CI output is reproducible.
    rng = random.Random(0)
    payloads["Deterministic random bytes (5KB)"] = rng.randbytes(5000)

    return payloads


def benchmark_payload(
    name: str,
    data: bytes,
    text_encoder: ByteTokenEncoder,
    direct_encoder: DirectIDEncoder,
) -> dict:
    b64 = base64.b64encode(data).decode("ascii")
    b64_tokens = count_tokens(b64)

    bt15 = text_encoder.encode(data)
    bt15_tokens = count_tokens(bt15)
    assert text_encoder.decode(bt15) == data

    did17_ids = direct_encoder.encode(data)
    assert direct_encoder.decode(did17_ids) == data

    compressed = lzma.compress(data)
    lzma_b64 = base64.b64encode(compressed).decode("ascii")
    lzma_b64_tokens = count_tokens(lzma_b64)

    lzma_bt15 = text_encoder.encode(compressed)
    lzma_bt15_tokens = count_tokens(lzma_bt15)
    assert text_encoder.decode(lzma_bt15) == compressed

    lzma_did17_ids = direct_encoder.encode(compressed)
    assert direct_encoder.decode(lzma_did17_ids) == compressed

    def saving(candidate: int) -> float:
        return round((1 - candidate / b64_tokens) * 100, 1) if b64_tokens else 0.0

    return {
        "name": name,
        "raw_bytes": len(data),
        "compressed_bytes": len(compressed),
        "base64_tokens": b64_tokens,
        "bt15_tokens": bt15_tokens,
        "did17_tokens": len(did17_ids),
        "lzma_b64_tokens": lzma_b64_tokens,
        "lzma_bt15_tokens": lzma_bt15_tokens,
        "lzma_did17_tokens": len(lzma_did17_ids),
        "bt15_saving": saving(bt15_tokens),
        "did17_saving": saving(len(did17_ids)),
        "lzma_b64_saving": saving(lzma_b64_tokens),
        "lzma_bt15_saving": saving(lzma_bt15_tokens),
        "lzma_did17_saving": saving(len(lzma_did17_ids)),
    }


def main() -> None:
    print("ByteToken synthetic developer-payload benchmark")
    print(f"Target tokenizer: {TARGET_TOKENIZER}")
    print("Direct-ID columns are local representation counts, not hosted-API claims.\n")

    text_encoder = ByteTokenEncoder(
        tokenizer=TARGET_TOKENIZER, bit_width=15
    )
    direct_encoder = DirectIDEncoder(
        tokenizer=TARGET_TOKENIZER, bit_width=17
    )

    rows = [
        benchmark_payload(name, data, text_encoder, direct_encoder)
        for name, data in generate_synthetic_payloads().items()
    ]

    header = (
        f"{'Payload':<36} {'Bytes':>8} {'B64':>8} {'BT15':>8} "
        f"{'DID17*':>8} {'LZ+B64':>8} {'LZ+BT15':>9} {'LZ+DID17*':>10}"
    )
    print(header)
    print("-" * len(header))
    for r in rows:
        print(
            f"{r['name']:<36} {r['raw_bytes']:>8,} {r['base64_tokens']:>8,} "
            f"{r['bt15_tokens']:>8,} {r['did17_tokens']:>8,} "
            f"{r['lzma_b64_tokens']:>8,} {r['lzma_bt15_tokens']:>9,} "
            f"{r['lzma_did17_tokens']:>10,}"
        )

    print("\nSavings relative to Base64 on the same uncompressed source bytes:")
    for r in rows:
        print(
            f"- {r['name']}: BT15 {r['bt15_saving']:+.1f}%, "
            f"DID17* {r['did17_saving']:+.1f}%, "
            f"LZMA+B64 {r['lzma_b64_saving']:+.1f}%, "
            f"LZMA+BT15 {r['lzma_bt15_saving']:+.1f}%, "
            f"LZMA+DID17* {r['lzma_did17_saving']:+.1f}%"
        )

    print("\n* Direct-ID values are local pre-tokenized-ID counts only.")


if __name__ == "__main__":
    main()
