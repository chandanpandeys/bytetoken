if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="ByteToken Lazy Atom Discovery")
    parser.add_argument("--tokenizer", default="o200k_base")
    parser.add_argument("--scan", action="store_true",
                        help="Scan and save pre-computed atom tables")
    parser.add_argument("--benchmark", action="store_true",
                        help="Run memory benchmark")
    parser.add_argument("--bit-width", type=int, default=15)
    args = parser.parse_args()

    print("=" * 65)
    print("  ByteToken Lazy Atom Discovery")
    print("=" * 65)

    if args.scan:
        print(f"\n  Scanning {args.tokenizer}...")
        scan_and_save(args.tokenizer)
        print("  Done!")
    
    elif args.benchmark:
        print(f"\n  Benchmarking {args.tokenizer} (bit_width={args.bit_width})...")
        lazy = LazyAtomDiscovery(args.tokenizer)
        results = lazy.benchmark_memory(bit_width=args.bit_width)
        
        print(f"\n  {'Strategy':<20} {'Memory':>12} {'Atoms':>8} {'Time':>10}")
        print(f"  {'─' * 52}")
        for name, stats in results.items():
            mem = stats.get("peak_memory_mb", stats.get("peak_memory_bytes", 0) / 1024 / 1024)
            print(f"  {name:<20} {mem:>10.2f}MB {stats['atoms_found']:>8} "
                  f"{stats['time_ms']:>8}ms")
    
    else:
        # Default: discover and display
        print(f"\n  Discovering atoms for {args.tokenizer} (bw={args.bit_width})...")
        
        # Try precomputed first
        precomputed = load_precomputed(args.tokenizer)
        if precomputed:
            target = 2 ** args.bit_width
            atoms = precomputed["space_nonmerging"][:target]
            print(f"  Loaded from pre-computed table: {len(atoms)} atoms")
        else:
            print(f"  No pre-computed table found. Running lazy discovery...")
            lazy = LazyAtomDiscovery(args.tokenizer)
            atoms = lazy.discover(bit_width=args.bit_width, chunk_size=500)
            print(f"  Discovered: {len(atoms)} atoms")
        
        print(f"  Target: {2 ** args.bit_width} atoms for {args.bit_width}-bit encoding")
        print(f"  Status: {'SUFFICIENT' if len(atoms) >= 2 ** args.bit_width else 'INSUFFICIENT'}")

    print(f"\n{'=' * 65}")
